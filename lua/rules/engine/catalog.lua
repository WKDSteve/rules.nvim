---@module 'rules.engine.catalog'
---@brief Build the reading documents ("catalogs") of a ruleset from its layouts and rule files.
---@description
--- A ruleset in the one-file-per-rule form has no document a person reads top
--- to bottom: the rules are files, and the documents are **generated**, like
--- `TASKS.md` of tasks.nvim. A *layout* says what a document is made of; the
--- generator puts it together and writes it, or with `check` only says whether
--- the file on disk is up to date (for CI).
---
--- A layout is a Markdown file whose frontmatter says `kind: layout` and
--- `output: <path of the document, relative to the ruleset root>`. Its body is
--- the document as it should read, with two kinds of lines taken for tokens:
---
---     {{rule DEP-06}}         replaced by the rule, as it reads in the document
---     {{toc}}                 replaced by the table of contents of the finished document
---     {{brief DEP-06}}        the rule in its brief form: one list item, id, title, rule text (`M.brief_lines`)
---     {{family DEP}}          every rule file of the family, in the order of the numbers (`{{family DEP brief}}`:
---                             each in its brief form)
---     {{refer DEP}}           nothing; the family counts as placed (`families: all`)
---
--- One token is **inline** (it may stand anywhere in a line of text): `{{range DEP}}` becomes the ids of the family as
--- a range, `DEP-01`..`DEP-20` in code spans (`M.range_text`); a gap in the numbers (a retired rule) splits it into
--- several ranges. It counts nothing as placed.
---
--- Two optional frontmatter keys: `families: all` (the layouts that say it hold every family of the ruleset, each
--- exactly once) and `folder: <path>` (the output lies in it, and nothing but the outputs of its layouts may: a
--- stale generated document there is removed).
---
--- A token is the whole line; whitespace after it is ignored, whitespace before it
--- makes the line text. Everything else (headings, introductions, separators) is
--- copied as it is. The order of the rules is the order of the tokens; the rule
--- files carry no order. A rule reads in the document as: its heading and the
--- text under it, and a ```rule block with `id` and `severity` put back in (the
--- file holds them in the frontmatter only; see `parser.read_rule_file`).
---
--- The output starts with a header line (`<!-- GENERATED by rules.nvim ... -->`).
--- The loader skips a file that starts with it, so a catalog and the rule files
--- it was made from never load as duplicates. Only such a file is ever replaced:
--- `build` refuses an `output` that is a layout, a rule file or another layout's
--- output, that leads out of the ruleset through a link, or that exists and was
--- not generated (see `M.build`).
---
--- Pure: `render` takes the layout and a lookup for rule files and returns
--- text, `build` is the one function that touches the disk.

local parser = require("rules.engine.parser")
local frontmatter = require("lib.nvim.markdown.frontmatter")
local fswalk = require("rules.engine.fswalk")
local loader = require("rules.engine.loader")
local expand_path = require("lib.nvim.cross.fs.expand_path")
local is_subpath = require("lib.nvim.fs.is_subpath")

local M = {}

M.TOC_TOKEN = "{{toc}}"

--- The heading above the table of contents is not listed in it.
local TOC_HEADING = "table of content"

--- A `{{toc ...}}` token is short. Anything longer is refused before a pattern sees it: `%S+=%S+` retries a long run of
--- non-blanks from every byte.
local TOC_MAX_BYTES = 256

--- Index of the last byte of `s` that is not whitespace (0 when there is none). Walks back from the end, so it is
--- linear. The obvious `(.-)%s*$` retries the rest of a whitespace run from every byte inside it, so a long run in
--- the middle of a line costs seconds (lib.nvim's frontmatter names this SEC-32).
---@param s string
---@return integer
local function last_non_space(s)
  local i = #s
  while i > 0 and s:find("^%s", i) do
    i = i - 1
  end
  return i
end

-- ── table of contents ────────────────────────────────────────────────────────

--- The anchor of a heading. The hand-kept tables of contents of the existing
--- rulesets spell it in two ways, which `params` chooses between:
---   * `unicode = 0` (default): lower case, anything but ASCII letters, digits, `-`
---     and spaces dropped (an umlaut goes, it does not become `u`), runs of spaces
---     and hyphens one hyphen; `_` stays with `underscore = 1` (default), goes with 0;
---   * `unicode = 1`: the renderers' way: lower case, letters of any alphabet,
---     digits, `-` and `_` stay, punctuation goes, every space is a hyphen (a
---     dropped dash between two spaces leaves `--`).
---@param text string
---@param params? Rules.TocParams
---@return string
function M.slug(text, params)
  params = params or M.TOC_DEFAULTS
  if params.unicode == 1 then
    local out = {}
    for _, ch in ipairs(vim.fn.split(text, "\\zs")) do
      if #ch == 1 then
        if ch:match("[%w_%-]") then
          out[#out + 1] = ch:lower()
        elseif ch == " " then
          out[#out + 1] = "-"
        end
      else
        -- A letter or digit of any script stays, whether the script has case or not (Han, Hangul, Arabic, Thai,
        -- Devanagari): `charclass` is 0 for a blank, 1 for punctuation and symbols, 3 for an emoji, and 2 or the
        -- number of a script for a word character.
        -- Below U+0100 `charclass` follows the buffer's 'iskeyword', which would make the anchors depend on where the
        -- command runs (and keep the signs × and ÷): the Latin-1 letters are named here instead.
        local code = vim.fn.char2nr(ch)
        local keep
        if code < 0x100 then
          keep = code == 0xAA or code == 0xB5 or code == 0xBA or (code >= 0xC0 and code ~= 0xD7 and code ~= 0xF7)
        else
          local class = vim.fn.charclass(ch)
          keep = class >= 2 and class ~= 3
        end
        if keep then
          out[#out + 1] = vim.fn.tolower(ch)
        end
      end
    end
    return table.concat(out)
  end
  local keep = params.underscore == 1 and "[^%w_%- ]" or "[^%w%- ]"
  local s = text:lower():gsub(keep, "")
  s = s:gsub("[ %-]+", "-")
  s = s:gsub("^%-", ""):gsub("%-$", "")
  return s
end

--- The headings of a document, outside fenced code.
---@param lines string[]
---@return {level: integer, text: string}[]
local function headings(lines)
  local out = {}
  local fence = 0
  for _, line in ipairs(lines) do
    if fence > 0 then
      local ticks = line:match("^(`+)%s*$")
      if ticks and #ticks >= fence then
        fence = 0
      end
    elseif line:match("^```") then
      fence = #line:match("^(`+)")
    else
      local hashes, rest = line:match("^(#+)%s+(.*)$")
      if hashes and #hashes <= 6 then
        out[#out + 1] = { level = #hashes, text = rest:sub(1, last_non_space(rest)) }
      end
    end
  end
  return out
end

---@class Rules.TocParams
---@field max integer  the deepest heading level listed (2 to 6)
---@field base integer  indentation, in spaces, of the first level (level 2)
---@field step integer  further indentation, in spaces, per level
---@field unicode integer  1: anchors keep letters of any alphabet (see `slug`)
---@field underscore integer  0: an anchor drops `_` (only with `unicode = 0`)

--- What `{{toc}}` means without parameters: levels 2 to 4, level 2 indented by two
--- spaces and two more per level, ASCII anchors that keep `_` (the shape of
--- `LUA_NVIM.md`).
---@type Rules.TocParams
M.TOC_DEFAULTS = { max = 4, base = 2, step = 2, unicode = 0, underscore = 1 }

--- Parameters that are switches, not sizes.
---@type table<string, true>
local TOC_SWITCHES = { unicode = true, underscore = true }

--- Read a `{{toc ...}}` line: `{{toc}}` or `{{toc max=2 base=0 step=2 unicode=1}}`. The token is the whole line;
--- whitespace after it is ignored, whitespace before it makes the line text.
---@param line string
---@return Rules.TocParams|nil params  nil when the line is no table token
---@return string|nil err  set when it is one, but a bad one
function M.parse_toc_token(line)
  line = line:sub(1, last_non_space(line))
  if #line < 7 or line:sub(1, 5) ~= "{{toc" or line:sub(-2) ~= "}}" then
    return nil, nil
  end
  if #line > TOC_MAX_BYTES then
    return nil, ("table of contents token longer than %d bytes"):format(TOC_MAX_BYTES)
  end
  local inner = line:sub(6, -3)
  local first = inner:find("%S")
  local args = first and inner:sub(first, last_non_space(inner)) or ""
  local params = vim.deepcopy(M.TOC_DEFAULTS)
  for key, value in args:gmatch("(%S+)=(%S+)") do
    local n = tonumber(value)
    local limit = TOC_SWITCHES[key] and 1 or 8
    if params[key] == nil or not n or n ~= math.floor(n) or n < 0 or n > limit then
      return nil,
        (
          "bad table of contents parameter %s=%s (want max, base, step, unicode, underscore; "
          .. "whole numbers, the last two 0 or 1)"
        ):format(key, value)
    end
    params[key] = n
  end
  if args:gsub("%S+=%S+", ""):match("%S") then
    return nil, ("bad table of contents parameters %q"):format(args)
  end
  if params.max < 2 or params.max > 6 then
    return nil, "table of contents `max` must be 2 to 6"
  end
  return params, nil
end

--- The token that gives `params` (the shortest one).
---@param params Rules.TocParams
---@return string
function M.toc_token(params)
  local parts = {}
  for _, key in ipairs({ "max", "base", "step", "unicode", "underscore" }) do
    if params[key] ~= M.TOC_DEFAULTS[key] then
      parts[#parts + 1] = ("%s=%d"):format(key, params[key])
    end
  end
  if #parts == 0 then
    return M.TOC_TOKEN
  end
  return ("{{toc %s}}"):format(table.concat(parts, " "))
end

--- The table of contents of a document: one line per heading from level 2 to
--- `params.max` (the title is not listed, nor is the heading of the table
--- itself), indented, each a link to its anchor. A second heading with the same
--- anchor gets `-1`, `-2`, ... like the renderers do.
---@param lines string[]  the document, without the table
---@param params? Rules.TocParams  default `M.TOC_DEFAULTS`
---@return string[]
function M.toc_lines(lines, params)
  params = params or M.TOC_DEFAULTS
  local out = {}
  local seen = {}
  for _, h in ipairs(headings(lines)) do
    if h.level >= 2 and h.level <= params.max and h.text:lower() ~= TOC_HEADING then
      local slug = M.slug(h.text, params)
      local count = seen[slug]
      seen[slug] = (count or 0) + 1
      if count then
        slug = ("%s-%d"):format(slug, count)
      end
      local indent = params.base + params.step * (h.level - 2)
      out[#out + 1] = ("%s- [%s](#%s)"):format((" "):rep(indent), h.text, slug)
    end
  end
  return out
end

-- ── layout ───────────────────────────────────────────────────────────────────

---@class Rules.Layout
---@field output string  path of the document, relative to the ruleset root, with `/`
---@field lines string[]  the body, one entry per line
---@field folder string|nil  a folder of generated documents only: nothing but the outputs of the layouts that name it
---   (or a folder inside it) may lie in it
---@field families "all"|nil  every family of the ruleset stands in exactly one of the layouts that say this

--- Is `path` a place a layout may write to: relative, inside the root, a file name that is valid on every system?
--- (The spelling only: that no link on the way leads out of the root is checked where the file is written.)
---@param path any
---@return boolean ok
---@return string|nil why
local function safe_output(path)
  if type(path) ~= "string" or path == "" then
    return false, "`output` must be a non-empty string"
  end
  -- `:` anywhere, not just as a drive prefix: on NTFS `a/b:c.md` is a stream of the file `b`. The others are not
  -- valid in a Windows file name, so the layout would fail there only when it is written.
  if path:find('[%c\\:*?"<>|]') or path:match("^/") or path:match("/$") or path:find("//", 1, true) then
    return false, '`output` must be a relative path with `/` that names a file, without any of \\ : * ? " < > |'
  end
  for segment in path:gmatch("[^/]+") do
    if segment == ".." or segment == "." then
      return false, "`output` must stay inside the ruleset (no `.` or `..`)"
    end
    -- Windows drops a trailing space or dot, so `docs./x.md` is `docs/x.md`: a spelling no key can tell
    if segment:find("[ .]$") then
      return false, "`output` must not have a part that ends in a space or a dot"
    end
  end
  if not path:match("%.md$") then
    return false, "`output` must end in .md"
  end
  return true, nil
end

--- Read a layout from its text.
---@param text string
---@return Rules.Layout|nil layout
---@return string|nil err
function M.parse_layout(text)
  text = text:gsub("\r\n", "\n")
  local parsed = frontmatter.parse(text)
  if not parsed or not parsed.has_block or parsed.meta.kind ~= "layout" then
    return nil, "not a layout (the frontmatter needs `kind: layout`)"
  end
  local ok, why = safe_output(parsed.meta.output)
  if not ok then
    return nil, why
  end
  local families = parsed.meta.families
  if families ~= nil and families ~= "all" then
    return nil, "`families` can only be `all` (every family of the ruleset stands in one such layout)"
  end
  local folder = parsed.meta.folder
  if folder ~= nil then
    -- the same spelling rules as `output`, checked on a file name inside it
    local folder_ok = type(folder) == "string" and safe_output(folder .. "/x.md")
    if not folder_ok then
      return nil, "`folder` must be a relative path with `/` inside the ruleset"
    end
    if parsed.meta.output:sub(1, #folder + 1) ~= folder .. "/" then
      return nil, ("`output` %s is not inside `folder` %s"):format(parsed.meta.output, folder)
    end
  end
  local body = vim.split(parsed.body, "\n", { plain = true })
  if body[#body] == "" then
    body[#body] = nil
  end
  return { output = parsed.meta.output, lines = body, folder = folder, families = families }, nil
end

-- ── one rule in the document ─────────────────────────────────────────────────

--- How a rule reads in a document: the lines of its file with the ```rule
--- block (the identity lines put back in) at its place.
---@param rule_file Rules.RuleFile
---@return string[]
function M.segment_lines(rule_file)
  local lines = rule_file.lines
  local out = {}
  local function fence(rest_from, rest_to)
    out[#out + 1] = "```rule"
    out[#out + 1] = ('id = "%s",'):format(rule_file.id)
    out[#out + 1] = ('severity = "%s",'):format(rule_file.severity)
    for i = rest_from, rest_to do
      out[#out + 1] = lines[i]
    end
    out[#out + 1] = "```"
  end

  local block = rule_file.block
  if block then
    for i = 1, block.s - 1 do
      out[#out + 1] = lines[i]
    end
    fence(block.s + 1, block.e - 1)
    for i = block.e + 1, #lines do
      out[#out + 1] = lines[i]
    end
  else
    local split = parser.implicit_split(rule_file)
    for i = 1, split do
      out[#out + 1] = lines[i]
    end
    fence(1, 0)
    out[#out + 1] = ""
    for i = split + 1, #lines do
      out[#out + 1] = lines[i]
    end
  end
  return out
end

-- ── one rule in its brief form ───────────────────────────────────────────────

--- Does this paragraph start the reason or the evidence of a rule (where the brief form ends)?
---@param line string
---@return boolean
local function is_reason(line)
  return line:sub(1, #"Begründung:") == "Begründung:" or line:sub(1, #"Beleg:") == "Beleg:"
end

--- One paragraph as it stands in a list item: prose joined to one line, a list kept as its lines (indented by two).
---@param para string[]
---@param first boolean  the first paragraph goes on the item's own line, unindented
---@return string[]
local function brief_paragraph(para, first)
  if para[1]:match("^%s*[-*] ") or para[1]:match("^%s*%d+%. ") then
    local out = {}
    for _, line in ipairs(para) do
      out[#out + 1] = "  " .. line
    end
    return out
  end
  local words = {}
  for _, line in ipairs(para) do
    words[#words + 1] = vim.trim(line)
  end
  local text = table.concat(words, " ")
  return { first and text or ("  " .. text) }
end

--- How a rule reads in a compact document (what an agent loads into every session): one list item with its id, its
--- title and its rule paragraphs, the text under the heading up to the first paragraph that starts with
--- `Begründung:` or `Beleg:` (or a `---` line, or the next heading). Prose is joined to one line, a list keeps its
--- lines. The title is the heading without a leading `` `ID` — ``. A fenced block in the rule text is an error: the
--- brief form has no place for it, and dropping it would silently cut the rule short.
---@param rule_file Rules.RuleFile
---@return string[]|nil lines
---@return string|nil err
function M.brief_lines(rule_file)
  local lines = rule_file.lines
  if not rule_file.heading then
    return nil, "no heading that names the rule"
  end
  local heading_text = lines[rule_file.heading]:match("^#+%s+(.*)$") or ""
  heading_text = heading_text:sub(1, last_non_space(heading_text))
  local tick = "`" .. rule_file.id .. "`"
  local title = heading_text
  if heading_text:sub(1, #tick) == tick then
    title = heading_text:sub(#tick + 1):match("^%s+—%s+(.*)$") or heading_text
  end
  local block = rule_file.block
  local paras, para = {}, {}
  local in_fence, in_reason, fence_in_rule = false, false, false
  for i = rule_file.heading + 1, #lines do
    local line = lines[i]
    local text = true
    if block and i >= block.s and i <= block.e then
      -- the ```rule block is the rule's identity, not its text
      text = false
    elseif line:match("^%s*```") then
      in_fence = not in_fence
      fence_in_rule = fence_in_rule or not in_reason
      text = false
    elseif in_fence then
      text = false
    end
    if text then
      if #para == 0 and is_reason(line) then
        in_reason = true
      end
      if line == "---" or line:match("^#+%s") and #line:match("^(#+)") <= 6 then
        break
      elseif not line:find("%S") then
        if #para > 0 then
          paras[#paras + 1] = para
          para = {}
        end
      else
        para[#para + 1] = line
      end
    end
  end
  if #para > 0 then
    paras[#paras + 1] = para
  end
  local out = {}
  for _, p in ipairs(paras) do
    if is_reason(p[1]) then
      break
    end
    for _, l in ipairs(brief_paragraph(p, #out == 0)) do
      out[#out + 1] = l
    end
  end
  if #out == 0 then
    return nil, "no rule text before `Begründung:`/`Beleg:`"
  end
  if fence_in_rule then
    return nil, "a fenced block in the rule text has no place in the brief form; move it below `Begründung:`/`Beleg:`"
  end
  local item = ("- `%s` **%s**:"):format(rule_file.id, title)
  if out[1]:sub(1, 2) == "  " then
    -- a list as the first paragraph keeps its lines under the item line
    table.insert(out, 1, item)
  else
    out[1] = item .. " " .. out[1]
  end
  return out, nil
end

-- ── tokens ───────────────────────────────────────────────────────────────────

---@class Rules.LayoutToken
---@field kind "rule"|"brief"|"family"|"refer"
---@field name string  the rule id (`rule`, `brief`) or the family (`family`, `refer`)
---@field brief boolean|nil  `{{family FAM brief}}`

--- Read a rule or family token: `{{rule ID}}`, `{{brief ID}}`, `{{family FAM}}`, `{{family FAM brief}}`,
--- `{{refer FAM}}`. The token is the whole line; whitespace after it is ignored. Not the table of contents.
---@param line string
---@return Rules.LayoutToken|nil
function M.parse_token(line)
  local bare = line:sub(1, last_non_space(line))
  if bare:sub(1, 2) ~= "{{" or bare:sub(-2) ~= "}}" or #bare > TOC_MAX_BYTES then
    return nil
  end
  local word, name, rest = bare:match("^{{(%l+)%s+([^%s}]+)%s*(%l*)%s*}}$")
  if not word then
    return nil
  end
  if (word == "rule" or word == "brief" or word == "refer") and rest == "" then
    return { kind = word, name = name }
  end
  if word == "family" and (rest == "" or rest == "brief") then
    return { kind = "family", name = name, brief = rest == "brief" }
  end
  return nil
end

--- The number of a rule id, for the order inside a family (`DEP-06` -> 6).
---@param id string
---@return number
local function id_number(id)
  return tonumber(id:match("%-(%d+)$")) or math.huge
end

--- The ids of one family as the text `{{range FAM}}` becomes: runs of consecutive numbers as `A`..`B` in code spans, a
--- lone number as `A`, the runs joined by `, `. A gap shows as a split, never as a silent range over it.
---@param ids string[]  the family's ids, in order of the numbers (`M.families_of`)
---@return string
function M.range_text(ids)
  local runs = {}
  local prev
  for _, id in ipairs(ids) do
    local n = id_number(id)
    if prev and n == prev.n + 1 then
      prev.last, prev.n = id, n
    else
      prev = { first = id, last = id, n = n }
      runs[#runs + 1] = prev
    end
  end
  local out = {}
  for _, run in ipairs(runs) do
    out[#out + 1] = run.first == run.last and ("`%s`"):format(run.first) or ("`%s`..`%s`"):format(run.first, run.last)
  end
  return table.concat(out, ", ")
end

--- The rule files of a ruleset grouped by family, each list in the order of the numbers.
---@param ids string[]
---@return table<string, string[]>
function M.families_of(ids)
  local out = {}
  for _, id in ipairs(ids) do
    local family = parser.family_of(id)
    out[family] = out[family] or {}
    table.insert(out[family], id)
  end
  for _, list in pairs(out) do
    table.sort(list, function(a, b)
      local na, nb = id_number(a), id_number(b)
      if na ~= nb then
        return na < nb
      end
      return a < b
    end)
  end
  return out
end

-- ── the document ─────────────────────────────────────────────────────────────

---@alias Rules.RuleFileLookup fun(id: string): Rules.RuleFile|nil, string|nil

--- Put a document together from a layout.
---@param layout Rules.Layout
---@param lookup Rules.RuleFileLookup  the rule file of an id, or `nil, why`
---@param header string|nil  first line of the output
---@param families table<string, string[]>|nil  the rule files of each family, in order (`M.families_of`); without it
---   a `{{family}}` or `{{refer}}` token names no rule
---@return string|nil text  `"\n"` line endings, ends with a newline
---@return string[] problems  one per token that could not be filled
---@return string[] used  the ids that were put in, in order
---@return string[] placed  the families placed by `{{family}}` or `{{refer}}`, in order
function M.render(layout, lookup, header, families)
  families = families or {}
  local out = {}
  local problems = {}
  local used = {}
  local seen = {}
  local placed, placed_at = {}, {}
  local toc_at, toc_params
  if header then
    out[1] = header
  end

  ---@param n integer  the layout line
  ---@param id string
  ---@param brief boolean
  local function put(n, id, brief)
    if seen[id] then
      problems[#problems + 1] = ("layout line %d: rule %s is placed twice (line %d)"):format(n, id, seen[id])
      return
    end
    seen[id] = n
    local rule_file, why = lookup(id)
    if not rule_file then
      problems[#problems + 1] = ("layout line %d: rule %s: %s"):format(n, id, why or "not found")
      return
    end
    local lines, err
    if brief then
      lines, err = M.brief_lines(rule_file)
    else
      lines = M.segment_lines(rule_file)
    end
    if not lines then
      problems[#problems + 1] = ("layout line %d: rule %s: %s"):format(n, id, err)
      return
    end
    used[#used + 1] = id
    for _, seg in ipairs(lines) do
      out[#out + 1] = seg
    end
  end

  for n, line in ipairs(layout.lines) do
    -- trailing whitespace (an editor's leftover) does not stop a token from being one; the line is copied as it is
    local token = M.parse_token(line)
    local params, params_err = M.parse_toc_token(line)
    if params_err then
      problems[#problems + 1] = ("layout line %d: %s"):format(n, params_err)
    elseif params then
      if toc_at then
        problems[#problems + 1] = ("layout line %d: more than one {{toc}}"):format(n)
      else
        toc_at = #out + 1
        toc_params = params
        out[toc_at] = false
      end
    elseif token and (token.kind == "rule" or token.kind == "brief") then
      put(n, token.name, token.kind == "brief")
    elseif token then
      local ids = families[token.name]
      if not ids then
        problems[#problems + 1] = ("layout line %d: family %s has no rule file"):format(n, token.name)
      elseif placed_at[token.name] then
        problems[#problems + 1] = ("layout line %d: family %s is placed twice (line %d)"):format(
          n,
          token.name,
          placed_at[token.name]
        )
      else
        placed_at[token.name] = n
        placed[#placed + 1] = token.name
        -- `{{refer FAM}}` places the family without its rules: the layout says in its own words where it is read
        if token.kind == "family" then
          for _, id in ipairs(ids) do
            put(n, id, token.brief == true)
          end
        end
      end
    else
      -- `{{range FAM}}` stands inside a line of text; an unknown family is a problem, not a literal token
      local text = line:gsub("{{range%s+([^%s}]+)%s*}}", function(fam)
        local ids = families[fam]
        if not ids then
          problems[#problems + 1] = ("layout line %d: {{range %s}}: family %s has no rule file"):format(n, fam, fam)
          return ""
        end
        return M.range_text(ids)
      end)
      out[#out + 1] = text
    end
  end
  if #problems > 0 then
    return nil, problems, used, placed
  end
  if toc_at then
    local rest = {}
    for i, line in ipairs(out) do
      if i ~= toc_at then
        rest[#rest + 1] = line
      end
    end
    local toc = M.toc_lines(rest, toc_params)
    local with_toc = {}
    for i = 1, toc_at - 1 do
      with_toc[#with_toc + 1] = out[i]
    end
    for _, line in ipairs(toc) do
      with_toc[#with_toc + 1] = line
    end
    for i = toc_at + 1, #out do
      with_toc[#with_toc + 1] = out[i]
    end
    out = with_toc
  end
  return table.concat(out, "\n") .. "\n", {}, used, placed
end

--- The header line of a generated document.
---@param layout_rel string  the layout's path relative to the ruleset root
---@return string
function M.header(layout_rel)
  return ("%s from %s: do not edit, change the layout and the rule files and run :Rules catalog -->"):format(
    parser.GENERATED_PREFIX,
    (layout_rel:gsub("%-%-", "- -"):gsub(">", "&gt;"))
  )
end

-- ── the disk ─────────────────────────────────────────────────────────────────

---@param path string
---@return string|nil
local function read_file(path)
  local f = io.open(path, "rb")
  if not f then
    return nil
  end
  local text = f:read("*a")
  f:close()
  return text
end

--- Paths that differ only in case are one file on Windows and (by default) on macOS.
local CASE_INSENSITIVE = require("lib.nvim.cross.platform.case_blind")()

--- A key under which two spellings of one path are equal: normalized, and case-folded where the file system is.
---@param path string
---@return string
local function path_key(path)
  local key = vim.fs.normalize(path)
  if CASE_INSENSITIVE then
    key = key:find("[\128-\255]") and vim.fn.tolower(key) or key:lower()
  end
  return key
end

--- Did the generator write this text? The loader's own test (`parser.classify`), on the first line.
---@param text string
---@return boolean
local function is_generated(text)
  return parser.classify({ text:match("^[^\n]*") }) == "generated"
end

---@class Rules.CatalogResult
---@field layout string  the layout file
---@field output string  the document it makes
---@field status "written"|"unchanged"|"stale"|"removed"|"error"  `removed`: a stale document of a `folder`
---@field problems string[]
---@field unused string[]|nil  rule ids that are in the ruleset but in no layout (set on the first result only)

---@class Rules.CatalogOpts
---@field check? boolean  write nothing, say which documents are out of date
---@field adopt? boolean  overwrite an output that exists but is not a generated document (a hand-written one)

--- Make every document of the ruleset at `root`, or with `opts.check` only say
--- which ones are not up to date. A document is written only when its content
--- changed (compared with line endings ignored; an existing CRLF file stays CRLF).
---
--- A layout whose `output` would destroy something gets status `"error"` and nothing is written for it:
--- an output that is a layout, a rule file (or a document with rules), or the output of another layout; one
--- that, with the links on its way resolved, is not inside the ruleset; one that exists and is not a generated
--- document (unless `opts.adopt`: the caller says the layout takes that file over, which is what a deliberate
--- replacement of a hand-written document looks like).
---@param root string
---@param opts? Rules.CatalogOpts
---@return Rules.CatalogResult[] results
---@return string[] errors  problems with the ruleset itself (it did not load cleanly)
function M.build(root, opts)
  opts = opts or {}
  local base = vim.fs.normalize(vim.fn.fnamemodify(expand_path(root), ":p")):gsub("/+$", "")
  local results = {}

  -- one read and one classification per Markdown file, for the layouts, the files no output may replace, and the
  -- `unused` rules below
  local layouts = {}
  local kinds = {} ---@type table<string, Rules.FileKind>
  local protected = {} ---@type table<string, string> path key -> what the file is
  for _, file in ipairs(fswalk.files(base)) do
    if file:match("%.md$") then
      local read_ok, lines = pcall(vim.fn.readfile, file)
      if read_ok then
        local kind = parser.classify(lines)
        kinds[file] = kind
        if kind == "layout" then
          layouts[#layouts + 1] = file
          protected[path_key(file)] = "a layout"
        elseif kind == "rule" then
          protected[path_key(file)] = "a rule file"
        end
      end
    end
  end
  table.sort(layouts)

  local rules, load_errors = loader.load({ base })
  local by_id = {}
  for _, rule in ipairs(rules) do
    by_id[rule.id] = rule
    local key = path_key(rule.source_file)
    protected[key] = protected[key] or "a document with rules"
  end

  local function lookup(id)
    local rule = by_id[id]
    if not rule then
      return nil, "not loaded"
    end
    local rule_file, errs = parser.read_rule_file(rule.source_file)
    if not rule_file then
      return nil, errs[1] or "not a rule file"
    end
    return rule_file, nil
  end

  local claimed = {} ---@type table<string, string> path key -> the layout that writes it

  --- Why the layout `rel` may not write `out`, or nil. Claims `out` for the layout when it may.
  ---@param rel string  the layout, relative to the root
  ---@param output string  as the layout spells it
  ---@param out string  absolute
  ---@return string|nil
  local function output_refusal(rel, output, out)
    -- a directory link on the way (a symlink, a junction) would carry the write, and the `mkdir` before it, out of the
    -- ruleset: the real path of what is written has to be inside the real root (a missing tail is resolved from its
    -- nearest existing parent)
    if not is_subpath(out, base, { realpath = true, ignore_case = CASE_INSENSITIVE }) then
      return ("%s: `output` %s leaves the ruleset (a link on its way points elsewhere)"):format(rel, output)
    end
    local key = path_key(out)
    if protected[key] then
      return ("%s: `output` %s is %s, it would be overwritten"):format(rel, output, protected[key])
    end
    if claimed[key] then
      return ("%s: `output` %s is already the output of %s"):format(rel, output, claimed[key])
    end
    claimed[key] = rel
    return nil
  end

  -- a family token names the rule files of the family (a rule in a document is in that document already)
  local file_ids = {}
  for _, rule in ipairs(rules) do
    if kinds[rule.source_file] == "rule" then
      file_ids[#file_ids + 1] = rule.id
    end
  end
  local families = M.families_of(file_ids)

  local placed = {}
  local family_home = {} ---@type table<string, string> family -> the `families: all` layout it stands in
  local all_results = {} ---@type Rules.CatalogResult[] the results of the `families: all` layouts
  local folders = {} ---@type table<string, string> folder -> the first layout that names it
  local in_folder = {} ---@type {folder: string, key: string}[] the outputs of the layouts with a `folder`
  for _, layout_path in ipairs(layouts) do
    local rel = layout_path:sub(#base + 2)
    local result = { layout = layout_path, output = "", status = "error", problems = {} }
    results[#results + 1] = result
    local text = read_file(layout_path)
    local layout, why = M.parse_layout(text or "")
    if not layout then
      result.problems[1] = ("%s: %s"):format(rel, why)
    else
      result.output = base .. "/" .. layout.output
      if layout.folder then
        folders[layout.folder] = folders[layout.folder] or layout_path
        in_folder[#in_folder + 1] = { folder = layout.folder, key = path_key(result.output) }
      end
      local rendered, problems, used, placed_families = M.render(layout, lookup, M.header(rel), families)
      for _, id in ipairs(used) do
        placed[id] = true
      end
      if layout.families == "all" then
        all_results[#all_results + 1] = result
        for _, family in ipairs(placed_families) do
          if family_home[family] then
            result.problems[#result.problems + 1] = ("%s: family %s stands in %s already"):format(
              rel,
              family,
              family_home[family]
            )
          else
            family_home[family] = rel
          end
        end
      end
      local refusal = output_refusal(rel, layout.output, result.output)
      if refusal then
        table.insert(result.problems, 1, refusal)
      end
      if not rendered then
        for _, p in ipairs(problems) do
          result.problems[#result.problems + 1] = ("%s: %s"):format(rel, p)
        end
      elseif not refusal then
        local existing = read_file(result.output)
        local was_crlf = existing ~= nil and existing:find("\r\n", 1, true) ~= nil
        local same = existing ~= nil and existing:gsub("\r\n", "\n") == rendered
        if same then
          result.status = "unchanged"
        elseif existing and existing:find("%S") and not opts.adopt and not is_generated(existing) then
          result.problems[1] = (
            "%s: %s exists and is not a generated document, so it is not overwritten "
            .. "(delete or move it to let the layout take its place)"
          ):format(rel, layout.output)
        elseif opts.check then
          result.status = "stale"
        else
          local out_text = was_crlf and rendered:gsub("\n", "\r\n") or rendered
          local ok_write, write_err = require("lib.nvim.fs.write.atomic")(result.output, out_text, { mkdirp = true })
          if ok_write then
            result.status = "written"
          else
            result.problems[1] = ("%s: %s"):format(result.output, write_err)
          end
        end
      end
    end
  end

  -- `families: all`: the layouts that say it together hold every family of the ruleset, each exactly once (twice is
  -- said above), so a new family cannot miss them
  if all_results[1] then
    local names = vim.tbl_keys(families)
    table.sort(names)
    for _, family in ipairs(names) do
      if not family_home[family] then
        local first = all_results[1]
        first.problems[#first.problems + 1] = ("family %s stands in no layout with `families: all` (%s)"):format(
          family,
          first.layout:sub(#base + 2)
        )
      end
    end
  end

  -- `folder`: the folder holds the outputs of the layouts that name it (or a folder inside it) and nothing else (a
  -- tool may take every file in it, as setup-claude-code links each one into ~/.claude/rules). A stale generated
  -- document is removed when the build had no error (a broken layout made nothing, so its document is kept); any
  -- other file is said.
  local folder_names = vim.tbl_keys(folders)
  table.sort(folder_names)
  local had_error = false
  for _, result in ipairs(results) do
    had_error = had_error or result.status == "error" or #result.problems > 0
  end
  for _, folder in ipairs(folder_names) do
    local owned = {}
    for _, entry in ipairs(in_folder) do
      if entry.folder == folder or entry.folder:sub(1, #folder + 1) == folder .. "/" then
        owned[entry.key] = true
      end
    end
    local dir = base .. "/" .. folder
    local files = {}
    if vim.fn.isdirectory(dir) == 1 then
      for name, ftype in vim.fs.dir(dir, { depth = math.huge }) do
        if ftype ~= "directory" then
          files[#files + 1] = dir .. "/" .. name:gsub("\\", "/")
        end
      end
    end
    table.sort(files)
    for _, file in ipairs(files) do
      if not owned[path_key(file)] then
        local rel = file:sub(#base + 2)
        local result = { layout = folders[folder], output = file, status = "error", problems = {} }
        results[#results + 1] = result
        local text = read_file(file) or ""
        if not file:match("%.md$") or not is_generated(text) or protected[path_key(file)] then
          result.problems[1] = ("%s is in `folder` %s, which holds generated documents only; move it"):format(rel, folder)
        elseif opts.check then
          result.status = "stale"
          result.problems[1] = ("%s is made by no layout of `folder` %s (run :Rules catalog to remove it)"):format(rel, folder)
        elseif had_error then
          result.problems[1] = ("%s is made by no layout of `folder` %s; kept, as the build had errors"):format(rel, folder)
        else
          local ok_remove, remove_err = os.remove(file)
          if ok_remove then
            result.status = "removed"
          else
            result.problems[1] = ("%s: %s"):format(rel, remove_err)
          end
        end
      end
    end
  end

  -- Only a rule file can be "in no layout": a rule in a document is in that document already. The kinds are known
  -- from the walk above, so no file is read again (a document with a hundred rules was read a hundred times).
  if results[1] then
    local unused = {}
    for _, rule in ipairs(rules) do
      if not placed[rule.id] and kinds[rule.source_file] == "rule" then
        unused[#unused + 1] = rule.id
      end
    end
    table.sort(unused)
    results[1].unused = unused
  end
  return results, load_errors
end

return M
